# ============== MAIN GENERATOR ==============
class ScriptGenerator:
    def __init__(self):
        self.templates = {
            'halal': ISLAMIC_TEMPLATES,
            'horror': HORROR_TEMPLATES,
            'mystery': MYSTERY_TEMPLATES,
            'kids': KIDS_TEMPLATES,
            'motivational': MOTIVATIONAL_TEMPLATES,
            'history': HISTORY_TEMPLATES,
            'science': SCIENCE_TEMPLATES,
            'poetry': POETRY_TEMPLATES,
            'facts': FACTS_TEMPLATES,
            'gaming': GAMING_TEMPLATES,
        }

    def generate_script(self, category: str) -> Dict:
        if category not in self.templates:
            category = 'halal'
        template = random.choice(self.templates[category])
        return {
            'title': template.get('title', ''),
            'title_urdu': template.get('title', ''),
            'script_urdu': template.get('script', ''),
            'arabic_text': template.get('arabic', ''),
            'arabic_source': template.get('source', ''),
            'category': category,
        }

    def get_template_titles(self, category: str) -> List[str]:
        if category not in self.templates:
            return []
        return [t.get('title', 'Untitled') for t in self.templates[category]]

    def get_template_by_title(self, category: str, title: str) -> Dict:
        for t in self.templates.get(category, []):
            if t.get('title') == title:
                return {
                    'title': t.get('title', ''),
                    'title_urdu': t.get('title', ''),
                    'script_urdu': t.get('script', ''),
                    'arabic_text': t.get('arabic', ''),
                    'arabic_source': t.get('source', ''),
                    'category': category,
                }
        return self.generate_script(category)


_script_generator = None

def get_script_generator() -> ScriptGenerator:
    global _script_generator
    if _script_generator is None:
        _script_generator = ScriptGenerator()
    return _script_generator
